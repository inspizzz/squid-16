#!/usr/bin/env python3
"""Run every experiment and write sim/results/ (results.json, report.md, three plots).

    python3 sim/extract_board.py     # only after the board changes (needs KiCad's pcbnew)
    python3 sim/run_all.py           # needs numpy, scipy, matplotlib, g++
"""
import json
import os
import time

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

import experiments as ex
import models as m

RES = ex.RES
SURFACE, INK, MUTED, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
BLUE, ORANGE = "#2a78d6", "#eb6834"


def style(ax, title, xlabel, ylabel):
    ax.set_facecolor(SURFACE)
    ax.set_title(title, loc="left", fontsize=12, color=INK, pad=12)
    ax.set_xlabel(xlabel, color=MUTED, fontsize=10)
    ax.set_ylabel(ylabel, color=MUTED, fontsize=10)
    ax.grid(True, color=GRID, linewidth=0.8)
    ax.tick_params(colors=MUTED, labelsize=9, length=0)
    for s in ax.spines.values():
        s.set_visible(False)


def plots(r):
    z = np.geomspace(1e4, 2e6, 200)
    fig, ax = plt.subplots(figsize=(7.2, 4.2), facecolor=SURFACE)
    for gain, col in ((4, BLUE), (8, ORANGE)):
        ax.plot(z / 1e3, np.abs(m.front_end(10.0, z, 100e3, gain)[0]) * 100, color=col, linewidth=2,
                label=f"gain {gain} (converter input about {m.adc_zin_diff(gain) / 1e6:.2g} MOhm)")
    ax.set_xscale("log"); ax.set_ylim(0, 100)
    style(ax, "Signal reaching the converter, by contact impedance", "pin contact impedance (kOhm)", "% of scalp signal kept")
    ax.legend(frameon=False, fontsize=9, labelcolor=INK)
    fig.tight_layout(); fig.savefig(os.path.join(RES, "signal_kept.png"), dpi=130); plt.close(fig)

    p = r["recording"].pop("_plot")
    fig, ax = plt.subplots(figsize=(7.2, 4.2), facecolor=SURFACE)
    keep = p["f"] <= 70
    ax.semilogy(p["f"][keep], np.sqrt(p["open"][keep]), color=BLUE, linewidth=2, label="eyes open")
    ax.semilogy(p["f"][keep], np.sqrt(p["closed"][keep]), color=ORANGE, linewidth=2, label="eyes closed")
    style(ax, f"Simulated recording, channel {p['channel']}: spectrum", "frequency (Hz)", "uV / sqrt(Hz)")
    ax.legend(frameon=False, fontsize=9, labelcolor=INK)
    fig.tight_layout(); fig.savefig(os.path.join(RES, "recording_spectrum.png"), dpi=130); plt.close(fig)

    names = list(r["monte_carlo"]["cases"])
    med = [r["monte_carlo"]["cases"][n]["hum_uV_per_mV_common_mode_median"] for n in names]
    p95 = [r["monte_carlo"]["cases"][n]["hum_uV_per_mV_common_mode_95th"] for n in names]
    fig, ax = plt.subplots(figsize=(8.6, 6.6), facecolor=SURFACE)
    y = np.arange(len(names))[::-1]
    ax.barh(y + 0.19, med, height=0.34, color=BLUE, label="median")
    ax.barh(y - 0.19, p95, height=0.34, color=ORANGE, label="95th percentile")
    for yi, a, b in zip(y, med, p95):
        ax.text(a, yi + 0.19, f" {a:.1f}", va="center", fontsize=8, color=INK)
        ax.text(b, yi - 0.19, f" {b:.1f}", va="center", fontsize=8, color=INK)
    ax.set_yticks(y); ax.set_yticklabels(names, fontsize=8.5, color=INK)
    style(ax, "Mains pickup on the worst channel", "false signal, uV per mV of common-mode voltage", "")
    ax.grid(axis="y", visible=False)
    ax.legend(frameon=False, fontsize=9, labelcolor=INK, loc="lower right")
    fig.tight_layout(); fig.savefig(os.path.join(RES, "mains_pickup.png"), dpi=130); plt.close(fig)


def report(r):
    L = []
    w = L.append
    w(f"# Squid-16 rev {r['board_revision']}: simulation results\n")
    w("Generated by `python3 sim/run_all.py`. Nothing here is a measurement: no board exists yet.")
    w("Tags: **[board]** read from the PCB file, **[datasheet]** typical datasheet figures, "
      "**[assumed]** a guess that the experiment sweeps or states.\n")
    x = r["wiring"]
    w("## 1. Wiring and data path [board + real firmware code]\n")
    w(f"- Module pins the copper connects to the converters match the firmware's pin numbers: "
      f"**{'all 9 checks pass' if x['gpio_all_ok'] else 'MISMATCH ' + str(x['gpio_checks'])}**.")
    w(f"- A different test tone on each of the 16 pins, through the firmware driver, packet code and the "
      f"recorder's decoder: **{16 - len(x['channels_in_wrong_place'])} of 16 channels come out under the "
      f"channel name the board gives that pin** (the footprint's label, which the silkscreen numbers and the docs are generated from), amplitude error {x['max_amplitude_error_percent']:.3f} %, "
      f"{x['packets_lost_or_misframed']} of {x['packets']} packets lost.")
    w("- Not covered: `main.cpp` (interrupts, Bluetooth, timing). The simulated converter is my reading of the datasheet.\n")
    x = r["retention"]
    w("## 2. Signal that reaches the converter [datasheet input impedance]\n")
    w("| Contact impedance | " + " | ".join(f"{z / 1e3:.0f} kOhm" for z in x["contact_ohm"]) + " |")
    w("|---|" + "---|" * len(x["contact_ohm"]))
    for g, row in x["fraction_kept_at_10Hz"].items():
        w(f"| Gain {g} | " + " | ".join(f"{v * 100:.0f} %" for v in row) + " |")
    w("\n![signal kept](signal_kept.png)\n")
    x = r["monte_carlo"]
    w(f"## 3. Random contact quality, {x['trials']:,} trials [assumed: {x['contact_range_ohm'][0] / 1e3:.0f} kOhm - "
      f"{x['contact_range_ohm'][1] / 1e6:.0f} MOhm per pin]\n")
    w("Hum is the false signal on the worst of the 16 channels per millivolt of mains voltage on the body "
      "relative to the board. How many millivolts there will be is unknown.\n")
    w("| Case | Signal kept (median) | Weakest / strongest channel | Hum, median | Hum, 95th pct |")
    w("|---|---|---|---|---|")
    for name, c in x["cases"].items():
        w(f"| {name} | {c['median_fraction_of_signal_kept'] * 100:.0f} % | {c['weakest_over_strongest_channel_median']:.2f} | "
          f"{c['hum_uV_per_mV_common_mode_median']:.1f} uV/mV | {c['hum_uV_per_mV_common_mode_95th']:.1f} uV/mV |")
    w(f"\nRan on: {x['device']}.\n\n![mains pickup](mains_pickup.png)\n")
    x = r["noise"]
    w(f"## 4. Noise floor [datasheet; contacts assumed {x['contact_ohm_assumed'] / 1e3:.0f} kOhm]\n")
    w("The last column assumes the noise is spread evenly over frequency, which flatters it: real low-frequency noise is higher.\n")
    w("| Gain | Converter | Contacts (thermal) | Buffer | Referred to the scalp, 0-125 Hz | In the 8-12 Hz band |")
    w("|---|---|---|---|---|---|")
    for g, n in x["by_gain"].items():
        w(f"| {g} | {n['converter_uV']:.2f} | {n['contacts_thermal_uV']:.2f} | {n['buffer_uV']:.2f} | "
          f"{n['referred_to_scalp_uV_rms']:.2f} uV rms | {n['in_8_12Hz_band_uV_rms']:.2f} uV rms |")
    w("")
    x = r["offsets"]
    w("## 5. Room for electrode DC offsets [datasheet range; offset spread assumed]\n")
    w("At gain 8 and above the converter's inputs draw a DC current. Through a dry contact that becomes a DC error "
      "of its own. The last two columns give the contact impedance at which that error alone fills the whole range: "
      "with the typical current from the datasheet graph, and with the table's worst-case figure as I interpret it.\n")
    w("| Gain | Largest offset that fits | Chance a channel clips, 25 mV rms spread | 50 mV | 100 mV | Contact limit, typical current | Contact limit, worst current |")
    w("|---|---|---|---|---|---|---|")
    for g, o in x["by_gain"].items():
        lim = (f"{o['contact_limit_kOhm_typical_current']:.0f} kOhm | {o['contact_limit_kOhm_worst_current']:.0f} kOhm"
               if "contact_limit_kOhm_typical_current" in o else "no such current | no such current")
        w(f"| {g} | {o['offset_limit_mV']:.0f} mV | {o['chance_any_channel_clips_sigma_25mV'] * 100:.0f} % | "
          f"{o['chance_any_channel_clips_sigma_50mV'] * 100:.0f} % | {o['chance_any_channel_clips_sigma_100mV'] * 100:.0f} % | {lim} |")
    w("")
    w("## 6. A simulated recording, eyes open then closed [source shape assumed]\n")
    sc = r["recording"]["scenario"]
    w(f"Alpha source: {sc['alpha_uv_at_peak_vs_far_reference']:.0f} uV at its peak against a distant reference, a smooth bump "
      f"{sc['bump_sigma_mm']:.0f} mm wide (sigma); mains {sc['mains_common_mode_mV_rms']:.0f} mV rms on the body; random contacts and offsets. "
      "No background brain activity is modelled, so the eyes-open baseline is only electronics noise and these counts are optimistic.\n")
    w("| Scenario | Largest real pin-to-reference difference | Channels showing alpha at 3x baseline | Channels saturated by input current | Best closed/open ratio |")
    w("|---|---|---|---|---|")
    for key, name in (("recording", f"board {sc['peak_offset_from_board_mm']:.0f} mm off the peak, gain 4"),
                      ("recording_gain8", f"board {sc['peak_offset_from_board_mm']:.0f} mm off the peak, gain 8"),
                      ("recording_on_peak", "board centred on the peak, gain 4")):
        y = r[key]
        w(f"| {name} | {y['largest_true_difference_uV']:.1f} uV | {y['channels_with_alpha_3x_above_baseline']} of 16 | "
          f"{len(y['channels_saturated_by_input_current'])} | {y['best_closed_over_open']:.1f} |")
    hum = [c["mains_uV_rms"] for c in r["recording"]["per_channel"].values()]
    w(f"\nMains line in that recording: {min(hum):.0f}-{max(hum):.0f} uV rms per channel for the assumed 1 mV.\n\n![spectrum](recording_spectrum.png)\n")
    x = r["ble"]
    w("## 7. Bluetooth queue [assumed host behaviour]\n")
    w("Share of packets dropped by the firmware's 64-packet queue:\n")
    per = sorted({q["packets_per_event"] for q in x["rows"]})
    w("| Connection interval | " + " | ".join(f"{p} packets per event" for p in per) + " |")
    w("|---|" + "---|" * len(per))
    for iv in sorted({q["interval_ms"] for q in x["rows"]}):
        w(f"| {iv} ms | " + " | ".join(f"{next(q['lost_percent'] for q in x['rows'] if q['interval_ms'] == iv and q['packets_per_event'] == p):.0f} %" for p in per) + " |")
    w("")
    x = r["buffer"]
    w("## 8. Reference buffer stability [estimate, not SPICE]\n")
    w(f"Two-pole op-amp model fitted to the datasheet's overshoot curve (output resistance {x['fitted_output_resistance_ohm']:.0f} ohm, "
      f"second pole {x['fitted_second_pole_MHz']:.1f} MHz, fit error {x['fit_rms_error_percent_points']:.1f} percentage points).\n")
    w("| Case | Phase margin | Step overshoot |")
    w("|---|---|---|")
    for name, c in x["cases"].items():
        w(f"| {name} | {c['phase_margin_deg']:.0f} deg | {c['overshoot_percent']:.0f} % |")
    w("")
    with open(os.path.join(RES, "report.md"), "w") as f:
        f.write("\n".join(L) + "\n")


def main():
    t0 = time.time()
    r = {"board_revision": m.BOARD["revision"], "sample_rate_assumed": m.FS_DATA}
    r["wiring"] = ex.exp_wiring_and_data_path()
    r["retention"] = ex.exp_signal_retention()
    r["monte_carlo"] = ex.exp_monte_carlo()
    r["noise"] = ex.exp_noise()
    r["offsets"] = ex.exp_offset_headroom()
    r["recording"] = ex.exp_recording()
    r["recording_on_peak"] = ex.exp_recording(offset_mm=0.0); r["recording_on_peak"].pop("_plot")
    r["recording_gain8"] = ex.exp_recording(gain=8); r["recording_gain8"].pop("_plot")
    r["ble"] = ex.exp_ble_queue()
    r["buffer"] = ex.exp_buffer_stability()
    plots(r)
    report(r)
    r["seconds"] = round(time.time() - t0, 1)
    with open(os.path.join(RES, "results.json"), "w") as f:
        json.dump(r, f, indent=1, default=float)
    print(f"done in {r['seconds']} s on {r['monte_carlo']['device']}; results in sim/results/")


if __name__ == "__main__":
    main()
